create type devos_private.event_origin as enum ('call', 'rule', 'owner', 'job');

-- Event (B 3.13). role_class comes from the caller's verified token, or is owner for an owner-only function (DM-31);
-- never declared. tx_id is the writing transaction (export and monitoring order by it and the object revision, B 3.13).
-- The ledger transfer's event payload rule and its idempotency index (EV-C02-005 section 15, S1 and S2) are not here:
-- 20261014182601_w08_ledger_transfer_schema.sql builds them after their tests merged (W-C02-08 point 9; the record).
-- Identity columns here are "by default", so that a direct write is refused by the privilege check itself, never first
-- by the identity rule (the record, section 4).
create table devos_private.event (
  id bigint generated by default as identity primary key,
  aggregate_type text not null check (aggregate_type ~ '^[a-z][a-z0-9_]*$'),
  aggregate_id uuid not null,
  aggregate_revision integer check (aggregate_revision >= 1),
  tx_id xid8 not null default pg_current_xact_id(),
  event_type text not null check (event_type ~ '^[a-z][a-z0-9_]*$'),
  payload jsonb not null default '{}' check (jsonb_typeof(payload) = 'object'),
  role_class text not null check (role_class in ('devos_calisma', 'devos_denetim', 'devos_sinav', 'devos_kurulum',
                                                 'devos_ci', 'devos_backup', 'owner')),
  origin devos_private.event_origin not null,
  declared_session_id text,
  created_at timestamptz not null default now(),
  exported_at timestamptz
);
create index event_aggregate_idx on devos_private.event (aggregate_type, aggregate_id);
create index event_tx_idx on devos_private.event (tx_id);
comment on table devos_private.event is 'Event (Appendix B 3.13); written by devos_api functions in the transaction of the change';

-- RejectedAttempt (B 3.13; EV-C02-002 DM-19). Two forms: a counted row for calls without a verified token (role_class
-- none, one row per function, reason code and hour, increased in place), and one row per call for a caller with a verified
-- token refused for another reason. No input content and nothing derived from a token is kept.
create table devos_private.rejected_attempt (
  id bigint generated by default as identity primary key,
  function_name text not null check (function_name <> ''),
  role_class text not null check (role_class in ('devos_calisma', 'devos_denetim', 'devos_sinav', 'devos_kurulum',
                                                 'devos_ci', 'devos_backup', 'none')),
  reason_code text not null check (reason_code ~ '^[a-z][a-z0-9_]*$'),
  counted_hour timestamptz,
  count integer check (count >= 1),
  declared_session_id text,
  reason text,
  target_ref uuid,
  target_revision integer check (target_revision >= 1),
  created_at timestamptz not null default now(),
  exported_at timestamptz,
  constraint rejected_attempt_form check (
    (counted_hour is not null and count is not null and role_class = 'none' and declared_session_id is null
       and reason is null and target_ref is null and target_revision is null
       and date_trunc('hour', counted_hour at time zone 'UTC') = counted_hour at time zone 'UTC')
    or (counted_hour is null and count is null and role_class <> 'none'))
);
create unique index rejected_attempt_counted_key on devos_private.rejected_attempt (function_name, reason_code, counted_hour)
  where counted_hour is not null;
comment on table devos_private.rejected_attempt is 'RejectedAttempt (Appendix B 3.13; EV-C02-002 DM-19)';
